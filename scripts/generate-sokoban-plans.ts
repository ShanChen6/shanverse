// Solves every Sokoban level and writes the hint plans the game shows:
// which crate goes to which pad, in order. Run after adding or editing a
// level:  pnpm sokoban:plans
// logic.test.ts fails if the committed file no longer matches the levels.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { LEVELS } from "../src/features/games/sokoban/levels";
import { parseLevel, planFromSolution, type PlanStep } from "../src/features/games/sokoban/logic";
import { solve } from "../src/features/games/sokoban/solver";

const OUTPUT = fileURLToPath(new URL("../src/features/games/sokoban/plans.generated.ts", import.meta.url));

const plans: Record<string, PlanStep[]> = {};
for (const level of LEVELS) {
  const state = parseLevel(level.map);
  const started = Date.now();
  const solution = solve(state);
  if (!solution) throw new Error(`Level "${level.id}" has no solution`);
  plans[level.id] = planFromSolution(state, solution);
  console.log(`${level.id}: ${solution.length} moves, ${plans[level.id].length} crates (${Date.now() - started} ms)`);
}

const body = Object.entries(plans)
  .map(([id, plan]) => `  ${JSON.stringify(id)}: [${plan.map((s) => `{ crate: ${s.crate}, goal: ${s.goal} }`).join(", ")}],`)
  .join("\n");

writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-sokoban-plans.ts. Do not edit by hand:
// run \`pnpm sokoban:plans\` after changing a level.
// Each plan lists crates (by starting cell) and their pads, in the order a
// shortest solution finishes them.

import type { PlanStep } from "./logic";

export const PLANS: Record<string, PlanStep[]> = {
${body}
};
`,
);
console.log(`Wrote ${OUTPUT}`);
